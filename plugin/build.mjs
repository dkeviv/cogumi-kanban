// Bundles the TypeScript sources (and zod) into dependency-free ES modules in dist/,
// so the installed plugin needs no package-manager step (PRD PLG 01).
import { build } from 'esbuild';

const entries = {
    server: 'src/server/main.ts',
    cli: 'src/cli/main.ts',
    hook: 'src/hook/session-start.ts',
    lib: 'src/lib.ts',
};
for (const [name, entry] of Object.entries(entries)) {
    await build({
        entryPoints: [entry],
        outfile: `dist/${name}.mjs`,
        bundle: true,
        platform: 'node',
        format: 'esm',
        target: 'node22.13',
        legalComments: 'none',
        banner: { js: '// Generated by build.mjs from src/. Do not edit.' },
        logLevel: 'warning',
    });
}
console.log('Built dist/{server,cli,hook,lib}.mjs');
